const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const files=['SmsCore.gs','SmsStore.gs','SmsWorkflow.gs','SmsUi.gs'];
const body='// Generated by tools/build-sms-bundle.cjs. Do not edit this bundle.\n'+files.map(f=>'\n// ---- '+f+' ----\n'+fs.readFileSync(path.join(root,'crm',f),'utf8')).join('\n');
const dir=path.join(root,'dist');fs.mkdirSync(dir,{recursive:true});fs.writeFileSync(path.join(dir,'SmsIntegration.gs'),body);
console.log('SmsIntegration.gs sha256 '+crypto.createHash('sha256').update(body).digest('hex'));
